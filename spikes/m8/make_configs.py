"""M8 spike Q3: pimd-rs configs (kind = "mace") for NMA in water, positions inline.

    python3 spikes/m8/make_configs.py nvt   --xyz BOX.xyz --model X.pt --dtype float32 --out C.toml
    python3 spikes/m8/make_configs.py drift --xyz BOX.xyz --model X.pt --dtype float64 --dt 0.5 ...

BOX.xyz is an extended xyz written by build_box.py (Lattice = cube) or, with --from-traj, the last
frame of a pimd-rs `trajectory.xyz` (P = 1) plus --box L (Å). The merged engine has no positions
file yet (M8a), so the positions go into `positions_angstrom`.
nvt:   P = 1, 300 K, PILE-L (centroid only at P = 1), tau0 100 fs, n_steps, trajectory every 20.
drift: [dynamics] method = "rpmd" at P = 1: per cycle `decor` thermostatted steps, a momentum
       redraw, then `seg` steps with Thermostat::Off; segments.csv has H/N at segment start/end.
"""

import argparse

MASS = {"H": 1.008, "C": 12.011, "N": 14.007, "O": 15.999}


def read_box(path, from_traj, box):
    lines = open(path).read().splitlines()
    if from_traj:
        # Last frame: frames are P·N, header, P·N lines.
        n = int(lines[0])
        frame = lines[-(n + 2):]
        return box, [ln.split() for ln in frame[2:]]
    n = int(lines[0])
    L = float(lines[1].split('Lattice="')[1].split()[0])
    return L, [ln.split() for ln in lines[2:2 + n]]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("kind", choices=["nvt", "drift"])
    ap.add_argument("--xyz", required=True)
    ap.add_argument("--from-traj", action="store_true")
    ap.add_argument("--box", type=float)
    ap.add_argument("--model", required=True)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--dtype", default="float32")
    ap.add_argument("--threads", type=int, default=1)
    ap.add_argument("--dt", type=float, default=0.5)
    ap.add_argument("--steps", type=int, default=20000)
    ap.add_argument("--decor", type=int, default=400)
    ap.add_argument("--seg", type=int, default=2000)
    ap.add_argument("--cycles", type=int, default=4)
    ap.add_argument("--seed", type=int, default=8100)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    L, atoms = read_box(a.xyz, a.from_traj, a.box)
    sym = [w[0] for w in atoms]
    pos = ", ".join(f"[{w[1]}, {w[2]}, {w[3]}]" for w in atoms)
    if a.kind == "nvt":
        n_steps, ckpt = a.steps, a.steps
    else:
        n_steps = ckpt = a.cycles * (a.decor + a.seg)
    s = f"""# M8 spike Q3 ({a.kind}); generated by spikes/m8/make_configs.py from {a.xyz}
[system]
n_atoms = {len(sym)}
masses_amu = [{", ".join(str(MASS[x]) for x in sym)}]
symbols = [{", ".join(f'"{x}"' for x in sym)}]
box_angstrom = {L}
positions_angstrom = [{pos}]

[potential]
kind = "mace"
model = "{a.model}"
device = "{a.device}"
dtype = "{a.dtype}"
threads = {a.threads}

[sampling]
temperature_kelvin = 300.0
n_beads = 1
dt_fs = {a.dt}
tau0_fs = 100.0
n_equil = 0
n_steps = {n_steps}
stride = 10
seed = {a.seed}

[output]
checkpoint_every = {ckpt}
trajectory_every = {20 if a.kind == "nvt" else 200}
"""
    if a.kind == "drift":
        s += f"""
[dynamics]
method = "rpmd"
decorrelation_steps = {a.decor}
segment_steps = {a.seg}
corr_stride = 10
n_lags = 10
"""
    open(a.out, "w").write(s)


if __name__ == "__main__":
    main()
