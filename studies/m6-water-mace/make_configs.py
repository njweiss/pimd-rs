"""Write the run configs of the M6c study (docs/experiments/m6-water-mace.md, "Protocol").

    python3 studies/m6-water-mace/make_configs.py pilot
    python3 studies/m6-water-mace/make_configs.py production --n-steps N [--n-steps-p32 N32]

Configs go to studies/m6-water-mace/configs/<set>/<run>.toml; paths inside are relative to the
repository root, where run.sh runs them. Seeds as in the plan: 1000 + P (H2O), +100 (D2O), +200
(HDO), +300 (xTB); the second P = 32 seed is 2032; the dt check: xTB P = 32 1432 (dt/2),
1532 (dt/4); MACE P = 32 3032 (dt/2).
"""

import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL = "ff_models/exports/m6c-off23-small-f64.pt"
# M5 start geometry (Å) and masses (amu); D = 2.014 amu.
POS = "[[0.0, 0.0, 0.1173], [0.0, 0.7572, -0.4692], [0.0, -0.7572, -0.4692]]"
MASSES = {"h2o": [15.999, 1.008, 1.008], "d2o": [15.999, 2.014, 2.014], "hdo": [15.999, 2.014, 1.008]}
SEED_OFFSET = {"h2o": 0, "d2o": 100, "hdo": 200}


def potential(kind, device):
    if kind == "mace":
        return f'kind = "mace"\nmodel = "{MODEL}"\ndevice = "{device}"\ndtype = "float64"\nthreads = 1\n'
    return 'kind = "socket"\naddress = "@ADDRESS@"\nn_clients = 4\ntimeout_s = 120.0\n'


def toml(species, kind, p, seed, n_equil, n_steps, device="cpu", dt_fs=0.5, traj_every=10):
    masses = ", ".join(str(m) for m in MASSES[species])
    return f"""# M6c {species} {kind} P = {p} (docs/experiments/m6-water-mace.md); generated by make_configs.py
[system]
n_atoms = 3
masses_amu = [{masses}]
symbols = ["O", "H", "H"]
positions_angstrom = {POS}

[potential]
{potential(kind, device)}
[sampling]
temperature_kelvin = 300.0
n_beads = {p}
dt_fs = {dt_fs}
tau0_fs = 20.0
n_equil = {n_equil}
n_steps = {n_steps}
stride = 1
seed = {seed}

[output]
checkpoint_every = {min(n_steps, 20000)}
trajectory_every = {traj_every}
"""


def runs(n_steps, n_steps_p32, n_equil):
    """(name, toml) of every production run in the plan."""
    out = []
    for p in (1, 4, 8, 16, 32):
        dev = "cuda" if p == 32 else "cpu"
        out.append((f"h2o_mace_p{p}", toml("h2o", "mace", p, 1000 + p, n_equil, n_steps_p32 if p == 32 else n_steps, dev)))
    out.append(("h2o_mace_p32_seed2", toml("h2o", "mace", 32, 2032, n_equil, n_steps_p32, "cuda")))
    for p in (1, 32):
        out.append((f"h2o_xtb_p{p}", toml("h2o", "xtb", p, 1300 + p, n_equil, n_steps)))
        for sp in ("d2o", "hdo"):
            dev = "cuda" if p == 32 else "cpu"
            out.append((f"{sp}_mace_p{p}", toml(sp, "mace", p, 1000 + SEED_OFFSET[sp] + p, n_equil, n_steps_p32 if p == 32 else n_steps, dev)))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("set", choices=["pilot", "production", "dtcheck"])
    ap.add_argument("--n-steps", type=int, default=200_000)
    ap.add_argument("--n-steps-p32", type=int)
    args = ap.parse_args()
    d = HERE / "configs" / args.set
    d.mkdir(parents=True, exist_ok=True)
    if args.set == "pilot":
        items = [(f"h2o_mace_p{p}_{dev}", toml("h2o", "mace", p, 1000 + p, 200, 2000, dev))
                 for p in (1, 4, 8, 16, 32) for dev in ("cpu", "cuda") if dev == "cpu" or p >= 16]
        items += [(f"h2o_xtb_p{p}", toml("h2o", "xtb", p, 1300 + p, 200, 2000)) for p in (1, 32)]
    elif args.set == "dtcheck":
        # Log 2026-11-03: xTB P = 32 at dt/2 and dt/4, same simulated times (10 ps + 100 ps) and
        # the same trajectory spacing (5 fs) as production.
        items = [(f"h2o_xtb_p32_dt{dt}", toml("h2o", "xtb", 32, seed, int(10_000 / dt), int(100_000 / dt),
                                                dt_fs=dt, traj_every=int(5 / dt)))
                 for dt, seed in ((0.25, 1432), (0.125, 1532))]
        # Log 2026-11-03: MACE P = 32 at dt/2 (plan "dt bias" rule), CUDA float64.
        items.append(("h2o_mace_p32_dt0.25", toml("h2o", "mace", 32, 3032, 40_000, 400_000, "cuda", dt_fs=0.25, traj_every=20)))
    else:
        items = runs(args.n_steps, args.n_steps_p32 or args.n_steps, 20_000)
    for name, text in items:
        (d / f"{name}.toml").write_text(text)
        print(d / f"{name}.toml")


if __name__ == "__main__":
    main()
