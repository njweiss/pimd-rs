"""Write the run configs of the M8b study (docs/experiments/m8-nma-water.md, "Protocol").

    python3 studies/m8-nma-water/make_configs.py pilot
    python3 studies/m8-nma-water/make_configs.py p1
    python3 studies/m8-nma-water/make_configs.py quantum   # after the P = 1 run (option b)

`pilot` and `p1` start from the box `nma_w216` of crates/pimd-cli/tests/data/m8_boxes.json, written
to out/start/nma_w216.xyz. `quantum` takes the first and the last frame of the P = 1 production
trajectory (out/p1/p1/trajectory.xyz) as out/start/p1_first.xyz and p1_last.xyz: P = 8, 16
and the first P = 32 start from the first, the second P = 32 from the last. Configs go to
studies/m8-nma-water/configs/<set>/<run>.toml; paths inside are relative to the repository root,
where run.sh runs them. Seeds: 8800 + P, second P = 32 8932; pilot 8700 + P.
"""

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
BOXES = ROOT / "crates/pimd-cli/tests/data/m8_boxes.json"
START = HERE / "out" / "start"
MODEL = "ff_models/exports/m8b-off23-small-f64.pt"
CHUNK = {1: 1, 8: 8, 16: 8, 32: 8}


def box():
    return json.loads(BOXES.read_text())["boxes"]["nma_w216"]


def write_xyz(path, symbols, positions, comment):
    lines = [str(len(symbols)), comment]
    lines += [f"{s} {x!r} {y!r} {z!r}" for s, (x, y, z) in zip(symbols, positions)]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def frames(traj):
    """(comment, [(symbol, x, y, z)]) of every frame of a P = 1 trajectory.xyz."""
    lines = traj.read_text().splitlines()
    k = 0
    while k < len(lines):
        n = int(lines[k])
        yield lines[k + 1], [l.split() for l in lines[k + 2:k + 2 + n]]
        k += n + 2


def toml(name, xyz, p, seed, n_equil, n_steps, traj_every=40, ckpt=1000):
    b = box()
    masses = ", ".join(str(m) for m in b["masses_amu"])
    return f"""# M8b {name} (docs/experiments/m8-nma-water.md); generated by make_configs.py
[system]
n_atoms = {b["n_atoms"]}
masses_amu = [{masses}]
positions_xyz = "{xyz.relative_to(ROOT)}"
box_angstrom = {b["box_angstrom"]!r}

[potential]
kind = "mace"
model = "{MODEL}"
device = "cuda"
dtype = "float32"
threads = 1
deterministic = true
beads_per_graph = {CHUNK[p]}

[sampling]
temperature_kelvin = 300.0
n_beads = {p}
dt_fs = 0.5
tau0_fs = 100.0
n_equil = {n_equil}
n_steps = {n_steps}
stride = 1
seed = {seed}

[output]
checkpoint_every = {min(ckpt, n_steps)}
trajectory_every = {traj_every}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("set", choices=["pilot", "p1", "quantum"])
    args = ap.parse_args()
    b = box()
    start = START / "nma_w216.xyz"
    write_xyz(start, b["symbols"], b["positions_angstrom"], "nma_w216 from m8_boxes.json")
    if args.set == "pilot":
        # Two lengths per P: the time per step is the difference over the extra steps (startup cancels).
        items = []
        for p, (short, long_) in {1: (200, 1000), 8: (40, 200), 16: (40, 200), 32: (40, 200)}.items():
            for n in (short, long_):
                items.append((f"p{p}_n{n}", toml(f"pilot P = {p}, {n} steps", start, p, 8700 + p, 0, n,
                                                 traj_every=n, ckpt=n)))
    elif args.set == "p1":
        items = [("p1", toml("P = 1", start, 1, 8801, 20_000, 40_000))]
    else:
        fr = list(frames(HERE / "out/p1/p1/trajectory.xyz"))
        for tag, (comment, atoms) in (("first", fr[0]), ("last", fr[-1])):
            write_xyz(START / f"p1_{tag}.xyz", [a[0] for a in atoms],
                      [tuple(float(v) for v in a[1:4]) for a in atoms], f"P = 1 production frame {comment}")
            print(f"p1_{tag}.xyz: {comment}")
        items = [(f"p{p}", toml(f"P = {p}", START / "p1_first.xyz", p, 8800 + p, 10_000, 40_000)) for p in (8, 16, 32)]
        items.append(("p32_seed2", toml("P = 32, second seed", START / "p1_last.xyz", 32, 8932, 10_000, 40_000)))
    d = HERE / "configs" / args.set
    d.mkdir(parents=True, exist_ok=True)
    for name, text in items:
        (d / f"{name}.toml").write_text(text)
        print(d / f"{name}.toml")


if __name__ == "__main__":
    main()
